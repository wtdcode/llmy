//! Mirror of the chat-completion response types from `async-openai` 0.36.1, with every
//! non-trivial struct/enum wrapped in [`WithOtherFields`] so unknown JSON fields survive a
//! deserialize → serialize round trip.
//!
//! This file is intentionally self-contained: it does not depend on `async_openai`. The wire
//! format aims to be byte-for-byte compatible with the OpenAI chat completions REST API.

use std::ops::{Deref, DerefMut};

use llmy_types::other::{OtherFields, WithOtherFields};
use serde::{Deserialize, Serialize};

// Shared types defined in req.rs (request side) but used in responses.
pub use crate::req::{
    ChatCompletionMessageCustomToolCall, ChatCompletionMessageToolCall,
    ChatCompletionMessageToolCalls, ChatCompletionMessageToolCallsRaw, CustomTool, FunctionCall,
    FunctionCallRaw, Role, ServiceTier,
};

// ---------------------------------------------------------------------------
// FinishReason
// ---------------------------------------------------------------------------

#[derive(Debug, Serialize, Deserialize, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum FinishReason {
    Stop,
    Length,
    ToolCalls,
    ContentFilter,
    FunctionCall,
}

#[derive(Debug, Serialize, Deserialize, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum CompletionFinishReason {
    Stop,
    Length,
    ContentFilter,
}

#[derive(Debug, Serialize, Deserialize, Clone, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum FunctionType {
    Function,
}

// ---------------------------------------------------------------------------
// Logprobs
// ---------------------------------------------------------------------------

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct TopLogprobsRaw {
    /// The token.
    pub token: String,
    /// The log probability of this token.
    pub logprob: f32,
    /// A list of integers representing the UTF-8 bytes representation of the token.
    pub bytes: Option<Vec<u8>>,
}
pub type TopLogprobs = WithOtherFields<TopLogprobsRaw>;

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct ChatCompletionTokenLogprobRaw {
    /// The token.
    pub token: String,
    /// The log probability of this token, if it is within the top 20 most likely tokens.
    pub logprob: f32,
    /// A list of integers representing the UTF-8 bytes representation of the token.
    pub bytes: Option<Vec<u8>>,
    /// List of the most likely tokens and their log probability, at this token position.
    pub top_logprobs: Vec<TopLogprobs>,
}
pub type ChatCompletionTokenLogprob = WithOtherFields<ChatCompletionTokenLogprobRaw>;

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct ChatChoiceLogprobsRaw {
    /// A list of message content tokens with log probability information.
    pub content: Option<Vec<ChatCompletionTokenLogprob>>,
    pub refusal: Option<Vec<ChatCompletionTokenLogprob>>,
}
pub type ChatChoiceLogprobs = WithOtherFields<ChatChoiceLogprobsRaw>;

