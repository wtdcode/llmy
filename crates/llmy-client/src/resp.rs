/// Breakdown of tokens used in a completion.
#[derive(Debug, Deserialize, Serialize, Clone, PartialEq, Default)]
pub struct CompletionTokensDetailsRaw {
    pub accepted_prediction_tokens: Option<u32>,
    /// Audio input tokens generated by the model.
    pub audio_tokens: Option<u32>,
    /// Tokens generated by the model for reasoning.
    pub reasoning_tokens: Option<u32>,
    /// When using Predicted Outputs, the number of tokens in the prediction that did not appear
    /// in the completion.
    pub rejected_prediction_tokens: Option<u32>,
}
pub type CompletionTokensDetails = WithOtherFields<CompletionTokensDetailsRaw>;

/// Breakdown of tokens used in a prompt.
#[derive(Debug, Deserialize, Serialize, Clone, PartialEq, Default)]
pub struct PromptTokensDetailsRaw {
    /// Audio input tokens present in the prompt.
    pub audio_tokens: Option<u32>,
    /// Cached tokens present in the prompt, i.e. read from the cache.
    pub cached_tokens: Option<u32>,
    /// The unadjusted number of prompt tokens written to cache (GPT-5.6+).
    /// Disjoint from `cached_tokens`; billed at the model's cache-write rate
    /// (1.25x the uncached input rate on GPT-5.6).
    pub cache_write_tokens: Option<u32>,
}
pub type PromptTokensDetails = WithOtherFields<PromptTokensDetailsRaw>;

/// Usage statistics for the completion request.
#[derive(Debug, Deserialize, Serialize, Clone, PartialEq, Default)]
pub struct CompletionUsageRaw {
    /// Number of tokens in the prompt.
    pub prompt_tokens: u32,
    /// Number of tokens in the generated completion.
    pub completion_tokens: u32,
    /// Total number of tokens used in the request (prompt + completion).
    pub total_tokens: u32,
    /// Breakdown of tokens used in the prompt.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub prompt_tokens_details: Option<PromptTokensDetails>,
    /// Breakdown of tokens used in a completion.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub completion_tokens_details: Option<CompletionTokensDetails>,
}
pub type CompletionUsage = WithOtherFields<CompletionUsageRaw>;

